def simulate_one(
    params_dict,
    z_max,
    M,
    default_params,
    SIMULATION_MODEL,
    cosmology,
    cols=None,
    errormodel=None,
    draw_errors=True,
    malmquist=False,
    survey_name=None,
    rng=None,
    N=None,
    i=None,
    out_df=False,
):
    """
    Simulate a single dataset of Type Ia supernovae.

    The supplied simulation parameters are merged with the default
    parameters, with values in ``params_dict`` taking precedence. These
    parameters are then used to configure a copy of ``SIMULATION_MODEL``
    before drawing a sample of Type Ia supernovae with ``skysurvey``.

    Optional Gaussian measurement noise can subsequently be applied to the
    simulated data.

    Parameters
    ----------
    params_dict : dict
        Dictionary containing simulation parameters that override the
        corresponding values in ``default_params``. The parameters
        ``"alpha"``, ``"beta"``, ``"mabs"``, ``"gamma"``, and
        ``"sigma_int"`` are used to configure the supernova simulation
        model.

    z_max : float
        Maximum redshift of the simulated supernova sample.

    M : int
        Number of Type Ia supernovae to simulate.

    cols : sequence of str
        Names of the columns to return when ``out_df=False``. Columns that
        are not present in the simulated dataframe are ignored.

    default_params : dict
        Default simulation parameters. Values in ``params_dict`` override
        corresponding entries in this dictionary.

    SIMULATION_MODEL : dict
        Base simulation model configuration passed to
        ``skysurvey.SNeIa.from_draw``. The model is deep-copied before its
        parameter-dependent values are modified.

    errormodel : optional
        Configuration used by ``apply_gaussian_noise`` to add Gaussian
        measurement noise to the simulated data. If ``None``, no additional
        noise is applied.

    rng : numpy.random.Generator, optional
        NumPy random number generator used for the simulation and noise
        generation. If ``None``, a new default generator is created.

    N : int, optional
        Total number of simulations in the surrounding simulation run.
        If provided together with ``i``, progress is periodically printed.

    i : int, optional
        Zero-based index of the current simulation in a larger simulation
        run. Used only for progress reporting when ``N`` is also provided.

    out_df : bool, optional
        If ``True``, return the complete simulated dataframe. If ``False``,
        return only the columns specified by ``cols`` as a dictionary.
        Default is ``False``.

    Returns
    -------
    pandas.DataFrame or dict
        If ``out_df=True``, returns the complete simulated dataframe.

        If ``out_df=False``, returns a dictionary mapping the requested
        column names to lists containing their simulated values.

    Notes
    -----
    A deep copy of ``SIMULATION_MODEL`` is used so that the parameter
    updates performed by this function do not modify the original model
    configuration.

    If the simulation model contains an ``"isup"`` component, its
    ``"func"`` entry is replaced by ``rng.binomial`` so that the supplied
    random-number generator is used for the corresponding sampling.
    """

    # Print progress
    if N is not None and i is not None:
        if (i + 1) % max(1, N // 10) == 0 or i == N - 1:
            print(f"Simulation {i + 1}/{N}", end="\r", flush=True)

    model = deepcopy(SIMULATION_MODEL)
    cosmo_temp = deepcopy(cosmology)

    magabs_map = {
        "sigma_int": "sigmaint",   # key renamed in the model
        "mabs": "mabs",
        "alpha": "alpha",
        "alpha_low": "alpha_low",
        "alpha_high": "alpha_high",
        "beta": "beta",
        "gamma": "gamma",
        "x1_ref": "x1_ref",
    }
    cosmo_keys = ["H0", "w"]
    
    for pname, kwname in magabs_map.items():
        if pname in params_dict:
            model["magabs"]["kwargs"][kwname] = params_dict[pname]
    
    for pname in cosmo_keys:
        if pname in params_dict:
            cosmo_temp[pname] = params_dict[pname]

    # Set survey-specific selection parameters (sampled value wins, else default)
    cut_loc, cut_scale = None, None
    if malmquist:
        if survey_name is None:
            raise ValueError("malmquist=True requires survey_name")
    
        sel = {**default_params, **params_dict}      # params_dict takes precedence
        loc_key = f"cut_loc_{survey_name}"
        scale_key = f"cut_scale_{survey_name}"
    
        missing = [k for k in (loc_key, scale_key) if k not in sel]
        if missing:
            raise KeyError(
                f"Malmquist selection for survey '{survey_name}' needs {missing} "
                f"in either params_dict (priors) or default_params"
            )
        cut_loc, cut_scale = sel[loc_key], sel[scale_key]
        if cut_scale <= 0:
            raise ValueError(f"{scale_key} must be > 0, got {cut_scale}")

    if rng is None:
        rng = np.random.default_rng()
    
    if "isup" in model:
        model["isup"]["func"] = rng.binomial

    if cosmology is not None:
        astropy_cosmo = ch.to_astropy(cosmo_temp)
        
    # Draw
    snia = skysurvey.SNeIa.from_draw(
        size=M,
        zmax=z_max,
        model=model,
        cosmology=astropy_cosmo
    )

    df = snia.data
    
    # Noise
    if errormodel is not None:
        df_err = apply_gaussian_noise(errormodel, data=df, rng=rng)
        if draw_errors:
            df = df_err
        else:
            err_cols = [c for c in df_err.columns if c.endswith("_err")]
            df = pd.concat([df, df_err[err_cols]], axis=1)
    
    
    # Apply malmquist bias (selection) if survey-specific parameters are provided
    if cut_loc is not None and cut_scale is not None:
        mag = np.asarray(df["magobs"], dtype=np.float32)

        # Detection probability
        p_detect = 1.0 - sci_spe.expit((mag - cut_loc) * cut_scale)

        # Bernoulli draw handled by numpy
        mask = rng.binomial(1, p_detect).astype(bool)

        df = df.loc[mask].reset_index(drop=True)
    

    if cols is None:
        if out_df:
            return df
        result = {
            col: df[col].to_numpy(copy=False)
            for col in df.keys()
        }
    else:
        if out_df:
            return df[cols]
        result = {
            col: df[col].to_numpy(copy=False)
            for col in cols
            if col in df
        }
    return result

def run_simulations(
    params_dict,
    N_total,
    columns,
    default_params,
    SIMULATION_MODEL,
    cosmology,
    noise_model,
    child_seeds,
    num_threads,
    surveys,        # {"ZTF": {"M": ..., "z_max": ...}, "LSST": {...}}
    draw_errors=True,
    malmquist=False,
    **simulate_kwargs,   # e.g. cosmo=...
):
    
    tasks = []
    for i in range(N_total):
        # independent stream per survey, so surveys aren't given identical random draws
        sub_seeds = child_seeds[i].spawn(len(surveys))
        for (tag, cfg), seed in zip(surveys.items(), sub_seeds):
            tasks.append((tag, i, cfg["z_max"], cfg["M"], seed))

    
    n_jobs = max(1, min(len(tasks) // 20, num_threads - 4))
    
    print("Running parallel simulations ..")
    raw = Parallel(n_jobs=n_jobs)(
        delayed(simulate_one)(
            {k: v[sim_idx] for k, v in params_dict.items()},
            z_max=zm,
            M=Mi,
            cols=columns,
            default_params=default_params,
            SIMULATION_MODEL=SIMULATION_MODEL,
            cosmology=cosmology,
            errormodel=noise_model,
            draw_errors=draw_errors,
            malmquist=malmquist,
            rng=np.random.default_rng(seed),
            survey_name=tag,
            N=len(tasks),
            i=idx,
            **simulate_kwargs,
        )
        for idx, (tag, sim_idx, zm, Mi, seed) in enumerate(tasks)
    )
    print(".. done")
    gc.collect()

    print("Grouping surveys ..")

    survey_ids = {tag: k + 1 for k, tag in enumerate(surveys.keys())}
    
    # Regroup by simulation index, add survey tag, concatenate across surveys
    per_sim = [[] for _ in range(N_total)]
    for (tag, i, *_), res in zip(tasks, raw):
        n = len(next(iter(res.values()))) if res else 0
        res = dict(res)
        res["survey"] = np.full(n, survey_ids[tag], dtype=np.int32)   # was dtype=object, tag
        per_sim[i].append(res)

    results = []
    for parts in per_sim:
        keys = [k for k in parts[0] if all(k in p for p in parts)]
        dropped = set().union(*(p.keys() for p in parts)) - set(keys)
        if dropped:
            warnings.warn(f"Columns not present in all surveys were dropped: {sorted(dropped)}")
        results.append({k: np.concatenate([p[k] for p in parts]) for k in keys})
    print(".. done")
    return results